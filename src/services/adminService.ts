export async function toggleMaintenanceMode(
  enable: boolean
): Promise<{ maintenance: boolean; message: string }> {
  await delay(300);
  if (enable) {
    localStorage.setItem(STORAGE_KEY_MAINTENANCE, 'true');
    return { maintenance: true, message: 'Đã kích hoạt Chế độ Bảo trì Hệ thống.' };
  } else {
    localStorage.removeItem(STORAGE_KEY_MAINTENANCE);
    return { maintenance: false, message: 'Hệ thống đã hoạt động bình thường trở lại.' };
  }
}

